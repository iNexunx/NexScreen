def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("'", "\\'")

def gen(lang, data, folder):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
    for k in KEYS:
        v = data.get(k, ES.get(k))
        if v is None:
            raise SystemExit("Missing value for key %s in %s" % (k, lang))
        lines.append("    <string name=\"%s\">%s</string>" % (k, esc(v)))
    lines.append("</resources>")
    path = os.path.join(RES, folder, "strings.xml")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", path)

def main():
    # base (Spanish)
    gen("es", ES, "values")
    for lang, data in LANG.items():
        folder = "values-in" if lang == "id" else "values-" + lang
        gen(lang, data, folder)

if __name__ == "__main__":
    main()
